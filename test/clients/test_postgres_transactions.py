"""Real PostgreSQL transaction, schema integrity and runtime role contracts."""

from dataclasses import replace
from uuid import uuid4

import pytest

from cli_agent_orchestrator.clients.postgres import DatabaseError, IntegrityError, connect
from cli_agent_orchestrator.clients.postgres.migrations import (
    ComponentMigration,
    SchemaMismatch,
    migrate_component,
    verify_component,
    verify_runtime_role,
)

pytestmark = pytest.mark.postgres
BASELINE = (
    ComponentMigration(
        "foundation_test",
        "main",
        1,
        (
            "CREATE TABLE foundation_records (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payload TEXT NOT NULL UNIQUE)",
        ),
        ("foundation_records",),
    ),
)


def test_borrowed_tuple_connection_returns_records_without_changing_owner(postgres_targets):
    import psycopg
    from psycopg import sql
    from psycopg.rows import tuple_row

    from cli_agent_orchestrator.clients.postgres import Connection

    target = postgres_targets.main
    migrate_component(target, BASELINE)
    with psycopg.connect(**target.connection_parameters(), row_factory=tuple_row) as raw:
        raw.execute(
            sql.SQL("SET search_path TO pg_catalog, {}").format(sql.Identifier(target.schema))
        )
        borrowed = Connection.borrow(raw, target)
        verify_component(borrowed, BASELINE)
        row = borrowed.execute(
            "INSERT INTO foundation_records(payload) VALUES (%s) RETURNING id,payload",
            ("borrowed",),
        ).fetchone()
        assert row["payload"] == row[1] == "borrowed"
        assert raw.row_factory is tuple_row
        assert raw.execute("SELECT payload FROM foundation_records").fetchone() == ("borrowed",)
        assert borrowed.in_transaction and not raw.closed
        raw.rollback()
        assert raw.execute(
            sql.SQL("SELECT count(*) FROM {}.foundation_records").format(
                sql.Identifier(target.schema)
            )
        ).fetchone() == (0,)


def test_native_named_ordinal_returning_and_rollback(postgres_targets):
    target = postgres_targets["main"]
    migrate_component(target, BASELINE)
    with connect(target) as connection:
        verify_runtime_role(connection)
        with pytest.raises(RuntimeError):
            with connection.transaction():
                row = connection.execute(
                    "INSERT INTO foundation_records(payload) VALUES (%s) RETURNING id,payload",
                    ("private",),
                ).fetchone()
                assert row[0] == row["id"]
                assert tuple(row) == (row["id"], "private")
                assert row == (row["id"], "private")
                raise RuntimeError("abort")
        assert connection.execute("SELECT count(*) FROM foundation_records").fetchone()[0] == 0


def test_repeatable_read_snapshot_and_readonly(postgres_targets):
    target = postgres_targets["main"]
    migrate_component(target, BASELINE)
    with connect(target, readonly=True) as snapshot, connect(target) as writer:
        assert snapshot.read_only
        assert not writer.read_only
        assert snapshot.execute("SELECT count(*) FROM foundation_records").fetchone()[0] == 0
        writer.execute("INSERT INTO foundation_records(payload) VALUES (%s)", ("new",))
        assert snapshot.execute("SELECT count(*) FROM foundation_records").fetchone()[0] == 0
        with pytest.raises(DatabaseError):
            snapshot.execute("INSERT INTO foundation_records(payload) VALUES (%s)", ("forbidden",))
        snapshot.rollback()


def test_migration_idempotence_and_catalog_tamper(postgres_targets):
    target = postgres_targets["main"]
    migrate_component(target, BASELINE)
    migrate_component(target, BASELINE)
    with connect(target, readonly=True) as reader:
        verify_component(reader, BASELINE)
    with connect(target.migration_target()) as owner:
        owner.execute(
            f'ALTER TABLE "{target.schema}".foundation_records ADD COLUMN unexpected TEXT'
        )
    with connect(target, readonly=True) as reader:
        with pytest.raises(SchemaMismatch):
            verify_component(reader, BASELINE)


def test_logical_store_identity_is_verified(postgres_targets):
    target = postgres_targets["main"]
    migrate_component(target, BASELINE)
    different = replace(target, store_id=str(uuid4()))
    with connect(different, readonly=True) as reader:
        with pytest.raises(SchemaMismatch):
            verify_component(reader, BASELINE)


def test_runtime_cannot_change_schema_proof_or_other_scope(postgres_targets):
    target = postgres_targets["main"]
    migrate_component(target, BASELINE)
    with connect(target) as connection:
        with pytest.raises(DatabaseError):
            connection.execute("DELETE FROM _cao_schema_migrations")
        with pytest.raises(DatabaseError):
            connection.execute("CREATE TABLE forbidden (id INTEGER)")
        with pytest.raises(DatabaseError):
            connection.execute("UPDATE _cao_store_identity SET store_id=%s", (str(uuid4()),))


@pytest.mark.parametrize("state", ["DISABLE", "ENABLE ALWAYS", "ENABLE REPLICA"])
def test_component_verification_rejects_changed_trigger_activation(postgres_targets, state):
    target = postgres_targets.main
    baseline = (
        ComponentMigration(
            "trigger_posture",
            "main",
            1,
            (
                "CREATE TABLE trigger_posture_records(id BIGINT PRIMARY KEY)",
                "CREATE FUNCTION trigger_posture_guard() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$",
                "CREATE TRIGGER trigger_posture_guard BEFORE INSERT ON trigger_posture_records FOR EACH ROW EXECUTE FUNCTION trigger_posture_guard()",
            ),
            ("trigger_posture_records",),
        ),
    )
    migrate_component(target, baseline)
    with connect(target.migration_target()) as owner:
        owner.execute(f"ALTER TABLE trigger_posture_records {state} TRIGGER trigger_posture_guard")
    with connect(target, readonly=True) as reader:
        with pytest.raises(SchemaMismatch):
            verify_component(reader, baseline)
