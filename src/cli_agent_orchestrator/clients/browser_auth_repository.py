"""Isolated native PostgreSQL authority store for browser authentication."""

from contextlib import contextmanager

from cli_agent_orchestrator.clients.postgres import (
    ConfigurationError,
    DatabaseError,
    DatabaseTarget,
    connect,
)
from cli_agent_orchestrator.clients.postgres.migrations import (
    ComponentMigration,
    SchemaMismatch,
    verify_component,
    verify_runtime_role,
)
from cli_agent_orchestrator.models.browser_auth import BrowserAuthError

_TABLES = (
    "auth_metadata",
    "browser_accounts",
    "browser_sessions",
    "browser_login_limits",
    "browser_auth_events",
)

BROWSER_AUTH_MIGRATIONS = (
    ComponentMigration(
        component="browser_auth",
        scope="auth",
        version=1,
        statements=(
            """CREATE TABLE auth_metadata (
                singleton_id SMALLINT PRIMARY KEY CHECK (singleton_id = 1),
                schema_version INTEGER NOT NULL,
                installation_id TEXT NOT NULL,
                auth_epoch BIGINT NOT NULL CHECK (auth_epoch >= 1),
                time_high_water DOUBLE PRECISION NOT NULL CHECK (time_high_water >= 0)
            )""",
            """CREATE TABLE browser_accounts (
                id TEXT PRIMARY KEY,
                username_normalized TEXT NOT NULL UNIQUE,
                password_scheme TEXT NOT NULL,
                password_salt TEXT NOT NULL,
                password_hash TEXT NOT NULL,
                password_params TEXT NOT NULL,
                account_version BIGINT NOT NULL CHECK (account_version >= 1),
                enabled BOOLEAN NOT NULL,
                principal_id TEXT NOT NULL,
                issuer TEXT NOT NULL,
                subject TEXT NOT NULL,
                principal_kind TEXT NOT NULL,
                scopes_json TEXT NOT NULL,
                created_at DOUBLE PRECISION NOT NULL,
                password_changed_at DOUBLE PRECISION NOT NULL
            )""",
            """CREATE TABLE browser_sessions (
                id TEXT PRIMARY KEY,
                account_id TEXT NOT NULL REFERENCES browser_accounts(id),
                secret_digest TEXT NOT NULL UNIQUE,
                auth_epoch BIGINT NOT NULL,
                account_version BIGINT NOT NULL,
                remembered BOOLEAN NOT NULL,
                idle_seconds BIGINT NOT NULL,
                absolute_seconds BIGINT NOT NULL,
                created_at DOUBLE PRECISION NOT NULL,
                last_activity_at DOUBLE PRECISION NOT NULL,
                absolute_expires_at DOUBLE PRECISION NOT NULL,
                access_expires_at DOUBLE PRECISION NOT NULL,
                revoked_at DOUBLE PRECISION,
                revoke_reason TEXT
            )""",
            "CREATE INDEX browser_sessions_account ON browser_sessions(account_id)",
            """CREATE TABLE browser_login_limits (
                bucket_digest TEXT PRIMARY KEY,
                bucket_kind TEXT NOT NULL,
                window_started_at DOUBLE PRECISION NOT NULL,
                failures BIGINT NOT NULL CHECK (failures >= 0),
                blocked_until DOUBLE PRECISION NOT NULL,
                updated_at DOUBLE PRECISION NOT NULL,
                pending_count BIGINT NOT NULL DEFAULT 0 CHECK (pending_count >= 0)
            )""",
            """CREATE TABLE browser_auth_events (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                occurred_at DOUBLE PRECISION NOT NULL,
                event_kind TEXT NOT NULL,
                outcome_code TEXT NOT NULL,
                account_id TEXT,
                session_id TEXT,
                peer_category TEXT NOT NULL,
                auth_method TEXT NOT NULL
            )""",
            "CREATE INDEX browser_auth_events_occurred_at ON browser_auth_events(occurred_at)",
        ),
        tables=_TABLES,
    ),
)


class BrowserAuthRepository:
    """Verify an installed auth schema and provide serialized authority transactions.

    This constructor never creates or repairs schema. A separate local-account
    setup path may initialize the installation metadata row after an explicit
    schema migration has already run.
    """

    def __init__(self, target: DatabaseTarget, installation_id: str | None = "local"):
        if not isinstance(target, DatabaseTarget) or target.scope != "auth":
            raise BrowserAuthError("auth_unavailable", 503)
        self.target = target
        self.installation_id = installation_id
        try:
            with connect(target, readonly=True) as db:
                verify_runtime_role(db)
                verify_component(db, BROWSER_AUTH_MIGRATIONS)
                row = db.execute("SELECT 1 FROM auth_metadata WHERE singleton_id=1").fetchone()
                if row is not None:
                    self._metadata(db)
        except (ConfigurationError, DatabaseError, SchemaMismatch) as exc:
            raise BrowserAuthError("auth_unavailable", 503) from exc

    def _connect(self):
        try:
            return connect(self.target)
        except (ConfigurationError, DatabaseError) as exc:
            raise BrowserAuthError("auth_unavailable", 503) from exc

    def _metadata(self, db, *, for_update=False):
        suffix = " FOR UPDATE" if for_update else ""
        row = db.execute("SELECT * FROM auth_metadata WHERE singleton_id=1" + suffix).fetchone()
        if (
            row is None
            or row["schema_version"] != 1
            or (self.installation_id is not None and row["installation_id"] != self.installation_id)
        ):
            raise BrowserAuthError("auth_unavailable", 503)
        return row

    def store_initialized(self) -> bool:
        try:
            with connect(self.target, readonly=True) as db:
                row = db.execute("SELECT * FROM auth_metadata WHERE singleton_id=1").fetchone()
                if row is None:
                    return False
                self._metadata(db)
                return True
        except (ConfigurationError, DatabaseError) as exc:
            raise BrowserAuthError("auth_unavailable", 503) from exc

    def initialize_store(self) -> None:
        """Create only initial metadata during owner-authorized account setup."""
        db = self._connect()
        try:
            db.begin()
            db.execute(
                "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
                (f"cao-browser-auth-install:{self.target.store_id}",),
            )
            row = db.execute(
                "SELECT * FROM auth_metadata WHERE singleton_id=1 FOR UPDATE"
            ).fetchone()
            if row is None:
                if self.installation_id is None:
                    raise BrowserAuthError("auth_unavailable", 503)
                occupied = db.execute("""SELECT EXISTS(SELECT 1 FROM browser_accounts)
                        OR EXISTS(SELECT 1 FROM browser_sessions)
                        OR EXISTS(SELECT 1 FROM browser_login_limits)
                        OR EXISTS(SELECT 1 FROM browser_auth_events)""").fetchone()[0]
                if occupied:
                    raise BrowserAuthError("auth_unavailable", 503)
                db.execute(
                    "INSERT INTO auth_metadata(singleton_id,schema_version,installation_id,auth_epoch,time_high_water) VALUES (1,1,%s,1,0)",
                    (self.installation_id,),
                )
            elif row["schema_version"] != 1 or row["installation_id"] != self.installation_id:
                raise BrowserAuthError("auth_unavailable", 503)
            db.commit()
        except BrowserAuthError:
            if db.in_transaction:
                db.rollback()
            raise
        except DatabaseError as exc:
            if db.in_transaction:
                db.rollback()
            raise BrowserAuthError("auth_unavailable", 503) from exc
        finally:
            db.close()

    @contextmanager
    def transaction(self):
        db = self._connect()
        try:
            db.begin()
            # The auth clock is a store-wide monotonic fence. Locking the one
            # metadata row is the store-wide synchronization boundary and
            # serializes login reservations, epoch changes, and session checks.
            self._metadata(db, for_update=True)
            yield db
            db.commit()
        except BrowserAuthError as exc:
            high_water = None
            if exc.status in (401, 429) and db.in_transaction:
                try:
                    row = db.execute(
                        "SELECT time_high_water FROM auth_metadata WHERE singleton_id=1"
                    ).fetchone()
                    high_water = row[0] if row else None
                except DatabaseError:
                    high_water = None
            if db.in_transaction:
                db.rollback()
            if high_water is not None:
                try:
                    db.begin()
                    db.execute(
                        "UPDATE auth_metadata SET time_high_water=GREATEST(time_high_water,%s) WHERE singleton_id=1",
                        (high_water,),
                    )
                    db.commit()
                except DatabaseError as storage_error:
                    if db.in_transaction:
                        db.rollback()
                    raise BrowserAuthError("auth_unavailable", 503) from storage_error
            raise
        except DatabaseError as exc:
            if db.in_transaction:
                db.rollback()
            raise BrowserAuthError("auth_unavailable", 503) from exc
        except BaseException:
            if db.in_transaction:
                db.rollback()
            raise
        finally:
            db.close()
