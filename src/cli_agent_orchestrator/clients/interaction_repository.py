def _json(value: object) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False)


def _safe_metadata(value: Mapping[str, object] | None) -> str:
    """Validate the small metadata vocabulary admitted to append-only history."""
    value = value or {}
    allowed_keys = {
        "answer_id",
        "assignment_id",
        "count",
        "delivery_id",
        "delivery_state",
        "delegation_id",
        "evidence_code",
        "expires_at",
        "group_id",
        "incarnation_id",
        "execution_mode",
        "lifecycle",
        "operation_key_hash",
        "observation_id",
        "outcome",
        "provider",
        "provider_version",
        "dialog_fingerprint",
        "provider_evidence_version",
        "question_id",
        "question_version",
        "recipient_kind",
        "response_capability",
        "required",
        "source_kind",
        "state",
        "terminal_id",
        "target_fingerprint",
        "turn_generation",
        "version",
        "wait_required",
        "wait_id",
        "work_item_id",
        "reason_code",
    }
    if not isinstance(value, Mapping):
        raise ValueError("interaction event metadata must be an object")
    if set(value) - allowed_keys:
        raise ValueError("interaction event metadata contains an unapproved field")
    clean: dict[str, object] = {}
    for key, item in value.items():
        if type(item) is bool or item is None:
            clean[key] = item
        elif type(item) is int and abs(item) <= 2**63 - 1:
            clean[key] = item
        elif isinstance(item, str) and len(item.encode("utf-8")) <= 256:
            if (
                key
                in {
                    "reason_code",
                    "evidence_code",
                    "outcome",
                    "state",
                    "lifecycle",
                    "delivery_state",
                    "response_capability",
                    "source_kind",
                    "recipient_kind",
                    "execution_mode",
                }
                and re.fullmatch(r"[A-Za-z0-9_.:-]{1,128}", item) is None
            ):
                raise ValueError("interaction event code is invalid")
            clean[key] = item
        else:
            raise ValueError("interaction event metadata values must be bounded scalars")
    encoded = _json(clean)
    if len(encoded.encode("utf-8")) > 1024:
        raise ValueError("interaction event metadata exceeds 1024 bytes")
    return encoded


class InteractionRepository:
    """Interaction tables on the same PostgreSQL target and transaction as Work."""

    def __init__(
        self,
        target: DatabaseTarget,
        work_repository: WorkRepository | None = None,
    ):
        self.target = target
        self.work_repository = work_repository or WorkRepository(target)
        work_target = self.work_repository.target
        if work_target.identity != target.identity:
            raise ValueError("interaction and Work repositories must share one PostgreSQL target")

    @contextmanager
    def transaction(self) -> Iterator[Connection]:
        with self.work_repository.transaction() as connection:
            yield connection

    @contextmanager
    def read_connection(self) -> Iterator[Connection]:
        with self.work_repository.read_snapshot() as connection:
            yield connection

    read_snapshot = read_connection

    def initialize(self) -> None:
        """Verify the installed schema; migrations run only under explicit bootstrap credentials."""
        with self.read_connection() as connection:
            self.verify(connection)

    @staticmethod
    def verify(connection: Connection) -> None:
        verify_component(connection, INTERACTION_MIGRATIONS)

    _verify = verify

    @staticmethod
    def append_event(
        connection: Connection,
        *,
        event_type: str,
        source_terminal_id: str | None,
        source_incarnation_id: str | None,
        actor_kind: str,
        actor_id: str | None,
        reason_code: str,
        metadata: Mapping[str, object] | None = None,
        group_id: str | None = None,
        question_id: str | None = None,
        event_id: str | None = None,
        created_at: float | None = None,
    ) -> int:
        if not connection.in_transaction:
            raise ValueError("interaction events require a caller-owned transaction")
        row = connection.execute(
            "INSERT INTO interaction_events(event_id,event_type,group_id,question_id,"
            "source_terminal_id,source_incarnation_id,actor_kind,actor_id,reason_code,metadata_json,created_at) "
            "VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING sequence",
            (
                event_id or str(uuid4()),
                event_type,
                group_id,
                question_id,
                source_terminal_id,
                source_incarnation_id,
                actor_kind,
                actor_id,
                reason_code,
                _safe_metadata(metadata),
                time.time() if created_at is None else created_at,
            ),
        ).fetchone()
        if row is None:
            raise InteractionSchemaMismatch("interaction event sequence was not assigned")
        return int(row["sequence"])

    @staticmethod
    def append_events(
        connection: Connection,
        events: Iterable[Mapping[str, object]],
    ) -> None:
        """Append a validated event batch in one caller-owned transaction."""
        if not connection.in_transaction:
            raise ValueError("interaction events require a caller-owned transaction")
        rows: list[tuple[object, ...]] = []
        for event in events:
            metadata = event.get("metadata")
            if metadata is not None and not isinstance(metadata, Mapping):
                raise ValueError("interaction event metadata must be an object")
            rows.append(
                (
                    event.get("event_id") or str(uuid4()),
                    event["event_type"],
                    event.get("group_id"),
                    event.get("question_id"),
                    event.get("source_terminal_id"),
                    event.get("source_incarnation_id"),
                    event["actor_kind"],
                    event.get("actor_id"),
                    event["reason_code"],
                    _safe_metadata(metadata),
                    time.time() if event.get("created_at") is None else event["created_at"],
                )
            )
        if not rows:
            return
        cursor = connection.executemany(
            "INSERT INTO interaction_events(event_id,event_type,group_id,question_id,"
            "source_terminal_id,source_incarnation_id,actor_kind,actor_id,reason_code,metadata_json,created_at) "
            "VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)",
            rows,
        )
        if cursor.rowcount != len(rows):
            raise InteractionSchemaMismatch("interaction event batch was not fully appended")

    @staticmethod
    def append_private_audit(
        connection: Connection,
        *,
        event_sequence: int,
        action: str,
        operator_principal_id: str,
        reason: str,
        created_at: float | None = None,
        target_terminal_id: str | None = None,
        target_incarnation_id: str | None = None,
        target_question_id: str | None = None,
    ) -> None:
        if not connection.in_transaction:
            raise ValueError("interaction private audit requires a caller-owned transaction")
        if action not in {"content_owner_designated", "question_cancelled", "delegation_revoked"}:
            raise ValueError("interaction private audit action is invalid")
        if not isinstance(reason, str) or not 1 <= len(reason.encode("utf-8")) <= 512:
            raise ValueError("interaction private audit reason must be 1..512 UTF-8 bytes")
        has_question_target = target_question_id is not None
        has_source_target = target_terminal_id is not None and target_incarnation_id is not None
        if has_question_target == has_source_target:
            raise ValueError("interaction private audit requires exactly one typed target")
        connection.execute(
            "INSERT INTO interaction_private_audit(event_sequence,action,operator_principal_id,"
            "target_terminal_id,target_incarnation_id,target_question_id,reason,created_at) "
            "VALUES(%s,%s,%s,%s,%s,%s,%s,%s)",
            (
                event_sequence,
                action,
                operator_principal_id,
                target_terminal_id,
                target_incarnation_id,
                target_question_id,
                reason,
                time.time() if created_at is None else created_at,
            ),
        )
